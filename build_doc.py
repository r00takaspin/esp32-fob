def p(text="", style=None, size=None, bold=False, color=None, space=4, italic=False):
    par = doc.add_paragraph(style=style)
    r = par.add_run(text)
    if size: r.font.size = Pt(size)
    r.bold = bold; r.italic = italic
    if color: r.font.color.rgb = color
    par.paragraph_format.space_after = Pt(space)
    return par

def bullet(text, size=10):
    par = doc.add_paragraph(style="List Bullet")
    r = par.add_run(text); r.font.size = Pt(size)
    par.paragraph_format.space_after = Pt(2)
    return par

def code(text):
    par = doc.add_paragraph()
    r = par.add_run(text)
    r.font.name = "Consolas"; r.font.size = Pt(9)
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "Consolas")
    par.paragraph_format.left_indent = Cm(0.6)
    par.paragraph_format.space_after = Pt(6)
    return par

def table(rows, widths, header=True, size=9.5):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.LEFT
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.cell(i, j)
            cell.width = Cm(widths[j])
            cell.text = ""
            par = cell.paragraphs[0]
            r = par.add_run(str(val)); r.font.size = Pt(size)
            r.bold = header and i == 0
            par.paragraph_format.space_after = Pt(1)
    return t

def img(path, width_cm, caption):
    doc.add_picture(path, width=Cm(width_cm))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    p(caption, size=8.5, color=SOFT, italic=True, space=8)

